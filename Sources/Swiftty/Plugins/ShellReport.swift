import Foundation

/// How probe output travels from the shell to Swiftty.
///
/// Before every prompt the shell integration calls `_swiftty_report`, which
/// runs each probe and prints the results in one escape sequence:
///
///     ESC ] 7337 ; swiftty ; <base64 of "key US value RS key US value RS …"> BEL
///
/// It travels in the terminal's own output stream, so it works the same on
/// this Mac and over a remote connection.
enum ShellReport {
    static let introducer = Data("\u{1b}]7337;swiftty;".utf8)

    /// Shell code (POSIX sh, sourced by zsh and bash) defining `_swiftty_report`.
    static func script(probes: [ShellProbe]) -> String {
        var out = "# Generated by Swiftty from its plugins' probes.\n"
        var calls = ""
        for (i, probe) in probes.enumerated() {
            let key = probe.key.filter { $0.isLetter || $0.isNumber || $0 == "." || $0 == "_" || $0 == "-" }
            out += "_swiftty_probe_\(i)() {\n\(probe.script)\n}\n"
            calls += "    printf '%s\\037' '\(key)'; _swiftty_probe_\(i) 2>/dev/null; printf '\\036'\n"
        }
        out += """
        _swiftty_report() {
          printf '\\033]7337;swiftty;%s\\007' "$(
            {
        \(calls)    } </dev/null | base64 | tr -d '\\n'
          )"
        }

        """
        return out
    }

    /// Decode the base64 payload of a report.
    static func decode(_ payload: Data) -> [String: String]? {
        guard let data = Data(base64Encoded: payload, options: .ignoreUnknownCharacters) else { return nil }
        var values: [String: String] = [:]
        for record in data.split(separator: 0x1e) {
            guard let sep = record.firstIndex(of: 0x1f) else { continue }
            let key = String(decoding: record[record.startIndex..<sep], as: UTF8.self)
            let value = String(decoding: record[record.index(after: sep)...], as: UTF8.self)
            values[key] = value.trimmingCharacters(in: .whitespacesAndNewlines)
        }
        return values
    }

    /// Run the probes from Swiftty itself, in `cwd` on this Mac.
    ///
    /// For shells that don't report (started by an older Swiftty, or just
    /// re-attached): close enough for anything that depends on the folder,
    /// though it can't see the shell's own variables.
    static func runLocally(probes: [ShellProbe], cwd: String) async -> [String: String] {
        let path = await LoginShell.path
        let script = script(probes: probes) + "_swiftty_report\n"
        return await Task.detached(priority: .userInitiated) {
            // Only the basics: Swiftty's own environment says nothing about the shell's
            // (an inherited CONDA_DEFAULT_ENV would show an environment the shell isn't in).
            let own = ProcessInfo.processInfo.environment
            var env = ["PATH": path]
            for key in ["HOME", "USER", "LOGNAME", "LANG", "TMPDIR"] { env[key] = own[key] }
            guard let out = Subprocess.run("/bin/sh", ["-c", script], cwd: cwd, environment: env) else { return [:] }
            var scanner = ShellReportScanner()
            return scanner.feed(Data(out.utf8)).reports.last ?? [:]
        }.value
    }
}

/// Takes shell reports out of a terminal output stream, across chunk boundaries.
struct ShellReportScanner {
    private var carry = Data()
    static let maxReport = 1 << 20

    struct Output {
        /// The stream without the reports.
        var passthrough = Data()
        var reports: [[String: String]] = []
    }

    mutating func feed(_ chunk: Data) -> Output {
        var out = Output()
        let intro = ShellReport.introducer
        // Fast path: nothing pending and no escape character at all.
        if carry.isEmpty, !chunk.contains(0x1b) {
            out.passthrough = chunk
            return out
        }
        let buf = carry + chunk
        carry = Data()
        var i = buf.startIndex
        var plainStart = i
        while let esc = buf[i...].firstIndex(of: 0x1b) {
            let rest = buf[esc...]
            if rest.count < intro.count {
                if intro.starts(with: rest) {
                    // Might be the start of a report: decide with the next chunk.
                    out.passthrough.append(buf[plainStart..<esc])
                    carry = Data(rest)
                    return out
                }
                i = buf.index(after: esc)
                continue
            }
            guard rest.starts(with: intro) else {
                i = buf.index(after: esc)
                continue
            }
            let payloadStart = esc + intro.count
            // Ends with BEL, or ESC \.
            guard let end = buf[payloadStart...].firstIndex(where: { $0 == 0x07 || $0 == 0x1b }) else {
                out.passthrough.append(buf[plainStart..<esc])
                if rest.count <= Self.maxReport { carry = Data(rest) }
                return out
            }
            var after = buf.index(after: end)
            if buf[end] == 0x1b {
                guard after < buf.endIndex else {
                    out.passthrough.append(buf[plainStart..<esc])
                    carry = Data(rest)
                    return out
                }
                // ESC \ ends the report; any other ESC starts something else and stays in the stream.
                after = buf[after] == UInt8(ascii: "\\") ? buf.index(after: after) : end
            }
            out.passthrough.append(buf[plainStart..<esc])
            if let values = ShellReport.decode(Data(buf[payloadStart..<end])) { out.reports.append(values) }
            plainStart = after
            i = after
        }
        out.passthrough.append(buf[plainStart...])
        return out
    }
}
